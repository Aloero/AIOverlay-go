package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"aioverlay/internal/config"
)

func main() {
	var configPath, outPath, goOutPath string
	flag.StringVar(&configPath, "config", "config.json", "portable app config")
	flag.StringVar(&outPath, "out", "build/winres.json", "generated winres json")
	flag.StringVar(&goOutPath, "go-out", "internal/buildinfo/generated.go", "generated runtime build identity")
	flag.Parse()

	cfg, err := config.NewStore(configPath).Load()
	if err != nil {
		fatal(err)
	}
	b := cfg.Build
	exe := filepath.Base(strings.TrimSpace(b.ExecutableName))
	if exe == "" {
		exe = "AIOverlay.exe"
	}
	if !strings.HasSuffix(strings.ToLower(exe), ".exe") {
		exe += ".exe"
	}
	version := normalizeVersion(b.Version)

	resources := map[string]any{
		"RT_MANIFEST": map[string]any{"#1": map[string]any{"0409": map[string]any{
			"description":     b.FileDescription,
			"minimum-os":      "win10",
			"execution-level": "as invoker",
			"dpi-awareness":   "per monitor v2",
			"long-path-aware": true,
		}}},
		"RT_VERSION": map[string]any{"#1": map[string]any{"0000": map[string]any{
			"fixed": map[string]any{"file_version": version, "product_version": version},
			"info": map[string]any{"0409": map[string]any{
				"CompanyName":      b.Company,
				"FileDescription":  b.FileDescription,
				"FileVersion":      version,
				"InternalName":     strings.TrimSuffix(exe, filepath.Ext(exe)),
				"OriginalFilename": exe,
				"ProductName":      b.ProductName,
				"ProductVersion":   version,
			}},
		}}},
	}
	if strings.TrimSpace(b.IconPath) != "" {
		icon, err := filepath.Abs(b.IconPath)
		if err != nil {
			fatal(err)
		}
		if _, err := os.Stat(icon); err != nil {
			fatal(fmt.Errorf("icon %s: %w", icon, err))
		}
		outDir, err := filepath.Abs(filepath.Dir(outPath))
		if err != nil {
			fatal(err)
		}
		relIcon, err := filepath.Rel(outDir, icon)
		if err != nil {
			fatal(err)
		}
		resources["RT_GROUP_ICON"] = map[string]any{"APP": map[string]any{"0000": filepath.ToSlash(relIcon)}}
	}
	data, err := json.MarshalIndent(resources, "", "  ")
	if err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(outPath, append(data, '\n'), 0o644); err != nil {
		fatal(err)
	}
	goSource := "// Code generated by cmd/buildmeta; DO NOT EDIT.\npackage buildinfo\n\nconst (\n\tCompany = " + strconv.Quote(b.Company) + "\n\tProductName = " + strconv.Quote(b.ProductName) + "\n\tVersion = " + strconv.Quote(b.Version) + "\n)\n"
	formatted, err := format.Source([]byte(goSource))
	if err != nil {
		fatal(fmt.Errorf("format build identity: %w", err))
	}
	if err := os.MkdirAll(filepath.Dir(goOutPath), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(goOutPath, formatted, 0o644); err != nil {
		fatal(err)
	}
	fmt.Println(exe)
}

func normalizeVersion(v string) string {
	parts := strings.Split(strings.TrimSpace(v), ".")
	clean := make([]string, 0, 4)
	for _, p := range parts {
		var digits strings.Builder
		for _, r := range p {
			if r >= '0' && r <= '9' {
				digits.WriteRune(r)
			} else {
				break
			}
		}
		if digits.Len() == 0 {
			clean = append(clean, "0")
		} else {
			clean = append(clean, digits.String())
		}
		if len(clean) == 4 {
			break
		}
	}
	for len(clean) < 4 {
		clean = append(clean, "0")
	}
	return strings.Join(clean, ".")
}

func fatal(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
